async function viewMemoryFile(filename, liElement) {
    document.querySelectorAll('#memory-list li').forEach(item => item.classList.remove('selected'));
    if(liElement) liElement.classList.add('selected');
    
    document.querySelectorAll('.viewer-tab').forEach(t => t.classList.remove('active'));
    document.querySelectorAll('.viewer-content').forEach(c => c.style.display = 'none');
    
    const tab = document.querySelector('.viewer-tab[data-target="memory-view-content"]');
    if(tab) tab.classList.add('active');
    
    const contentBox = document.getElementById('memory-view-content');
    if(contentBox) contentBox.style.display = 'block';

    try {
        const res = await fetch(`/api/memory/${filename}`);
        const data = await res.json();
        if (data.content) {
            contentBox.innerText = data.content;
        } else {
            contentBox.innerText = `Error loading file: ${data.error}`;
        }
    } catch (e) {
        contentBox.innerText = `Error loading file: ${e}`;
    }
}

